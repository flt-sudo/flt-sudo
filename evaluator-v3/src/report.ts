import type { RegistryResult } from "./registry.js";
import type { Draft, Plan } from "./schemas.js";
import type { ValidationRecord } from "./validation-record.js";

const list = (xs: string[]) => (xs.length ? xs.map((x) => `- ${x}`).join("\n") : "- (none)");

export function renderReport(plan: Plan, draft: Draft, reg: RegistryResult, vr: ValidationRecord): string {
  const ev = new Map(reg.records.map((r) => [r.id, r]));
  const cite = (ids: string[]) => (ids.length ? ` [${ids.join(", ")}]` : "");
  const crit = new Map(plan.criteria.map((c) => [c.id, c]));
  const s: string[] = [];
  s.push(`# Evaluation: ${plan.subject}`, "");
  s.push(`**Decision objective:** ${plan.decisionObjective}`, "");
  s.push(`## Verdict`, "", draft.verdict, "", `**Confidence:** ${draft.confidence}  ·  **Certified by quality gates:** ${vr.certified ? "yes" : "NO"}`, "");
  if (draft.correctedUserAssumptions.length) {
    s.push(`## Corrected assumptions`, "", ...draft.correctedUserAssumptions.map((a) => `- **Assumption:** ${a.assumption}\n  **Correction:** ${a.correction}${cite(a.evidenceIds)}`), "");
  }
  s.push(`## Criteria`, "");
  for (const a of draft.criteriaAssessments) {
    const c = crit.get(a.criterionId);
    s.push(`### ${a.criterionId} ${c?.name ?? ""} (weight ${c?.weight ?? "?"})`, "", a.assessment + cite(a.evidenceIds), "", `*Mechanisms:* ${a.mechanisms}`, "", `*Strengths:*`, list(a.strengths), "", `*Weaknesses:*`, list(a.weaknesses), "");
  }
  s.push(`## Key claims`, "", ...draft.claims.map((c) => `- **${c.id}**${c.material ? " (material)" : ""}: ${c.text}${cite([...c.evidenceIds, ...c.calculationIds])}`), "");
  if (draft.calculations.length) {
    s.push(`## Calculations (re-executed by code)`, "", "| id | purpose | expression | claimed | recomputed | ok |", "|---|---|---|---|---|---|");
    const checks = new Map(vr.checksExecuted.map((x) => [x.match(/Calculation (K\d+)/)?.[1], x]));
    for (const k of draft.calculations) {
      const line = checks.get(k.id) ?? "";
      const re = line.match(/= ([-\d.e+]+) \(claimed/)?.[1] ?? "n/a";
      s.push(`| ${k.id} | ${k.purpose} | \`${k.expression}\` | ${k.claimedResult} | ${re} | ${/match$/.test(line) ? "yes" : "NO"} |`);
    }
    s.push("");
  }
  s.push(`## Alternatives`, "", ...draft.alternatives.map((a) => `- **${a.option}:** ${a.comparison}`), "");
  s.push(`## Tradeoffs`, "", list(draft.tradeoffs), "");
  s.push(`## Edge cases and failure modes`, "", list(draft.edgeCasesAndFailureModes), "");
  s.push(`## Counterarguments`, "", ...draft.counterarguments.map((c) => `- **${c.argument}** — ${c.response}`), "");
  s.push(`## Practical implications`, "", list(draft.practicalImplications), "");
  s.push(`## Remaining uncertainty`, "", list(vr.remainingUncertainty), "");
  s.push(`## Further research that could change the conclusion`, "", list(draft.furtherResearchThatCouldChangeConclusion), "");
  s.push(`## Evidence registry`, "", "| id | class | provenance | claim | source |", "|---|---|---|---|---|");
  for (const r of ev.values()) s.push(`| ${r.id} | ${r.effectiveClassification}${r.effectiveClassification !== r.classification ? ` (claimed ${r.classification})` : ""} | ${r.provenance} | ${r.claim.replace(/\|/g, "/")} | ${r.source.ref} |`);
  if (reg.rejected.length) s.push("", "**Rejected evidence (not relied on):**", list(reg.rejected.map((r) => `${r.id}: ${r.reason}`)));
  s.push("", `## Validation record`, "", "_Generated by code from the tool log; not written by the model._", "");
  s.push(`1. **Research performed:** ${vr.researchPerformed.webSearches.length} web search(es), ${vr.researchPerformed.webFetches.length} fetch attempt(s), ${vr.researchPerformed.fixturesRead.length} supplied document(s) read.`);
  s.push(list(vr.researchPerformed.webSearches.map((w) => `search: "${w.query}" (${w.ok ? `${w.resultCount} results` : "failed"})`)));
  s.push(`2. **Sources inspected:**`, list(vr.sourcesInspected.map((x) => `${x.ref} (${x.how})`)));
  if (vr.sourcesCitedFromSearchSnippetsOnly.length) s.push(`   Cited from search snippets only (not opened):`, list(vr.sourcesCitedFromSearchSnippetsOnly));
  s.push(`3. **Checks executed:**`, list(vr.checksExecuted));
  s.push(`4. **Checks not executed:**`, list(vr.checksNotExecuted));
  s.push(`5. **Independent validation status:** ${vr.independentValidationStatus}`);
  s.push(`6. **Remaining uncertainty:** ${vr.remainingUncertainty.length} item(s), listed above.`);
  s.push(`7. **Revisions:** ${vr.revisions.count}`, list(vr.revisions.entries.map((e) => `cycle ${e.cycle} (${e.action}): ${e.reasons.join("; ")}`)));
  s.push(`8. **Final quality gates:**`);
  if (vr.finalQualityGates === "not run") s.push("- not run");
  else for (const [g, v] of Object.entries(vr.finalQualityGates)) s.push(`- ${v.pass ? "PASS" : "FAIL"} ${g}${v.findings.length ? `: ${v.findings.join(" | ")}` : ""}`);
  return s.join("\n") + "\n";
}
