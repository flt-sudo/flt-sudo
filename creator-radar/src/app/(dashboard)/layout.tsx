import { LogOut, Radar } from "lucide-react";
import { DataViewToggle } from "@/components/data-view-toggle";
import { Nav } from "@/components/nav";
import { Button } from "@/components/ui/button";
import { requireOperator } from "@/lib/auth";
import { getDataView, getSettings } from "@/lib/data/queries";
import { signOut } from "./actions";

export const dynamic = "force-dynamic";

export default async function DashboardLayout({ children }: { children: React.ReactNode }) {
  const { supabase, user } = await requireOperator();
  const settings = await getSettings(supabase);
  const view = await getDataView(settings);

  return (
    <div className="flex min-h-screen flex-col md:flex-row">
      <aside className="flex shrink-0 flex-col gap-6 border-b border-border p-4 md:w-60 md:border-r md:border-b-0">
        <div className="flex items-center gap-2 px-1">
          <span className="flex size-8 items-center justify-center rounded-lg bg-primary/15 text-primary">
            <Radar className="size-4" />
          </span>
          <span className="text-sm font-semibold tracking-tight">Creator Radar</span>
        </div>
        <Nav />
        <div className="mt-auto hidden flex-col gap-2 text-xs text-muted-foreground md:flex">
          <span className="truncate" title={user.email ?? undefined}>{user.email}</span>
          <form action={signOut}>
            <Button variant="ghost" size="sm" className="w-full justify-start px-2">
              <LogOut /> Sign out
            </Button>
          </form>
        </div>
      </aside>
      <div className="flex min-w-0 flex-1 flex-col">
        <header className="flex flex-wrap items-center justify-between gap-3 border-b border-border px-6 py-3">
          <p className="text-xs text-muted-foreground">
            Provider: <span className="font-medium text-foreground">{settings.provider_configuration.provider === "x" ? "X API" : "Mock (simulated)"}</span>
          </p>
          <div className="flex items-center gap-2">
            <DataViewToggle view={view} />
            <form action={signOut} className="md:hidden">
              <Button variant="ghost" size="icon" aria-label="Sign out">
                <LogOut />
              </Button>
            </form>
          </div>
        </header>
        {view === "simulated" && (
          <div className="border-b border-warning/30 bg-warning/10 px-6 py-2 text-xs text-warning">
            You are viewing <strong>simulated</strong> data generated by the mock provider. None of these accounts or posts are real discoveries.
          </div>
        )}
        <main className="flex-1 p-6">{children}</main>
      </div>
    </div>
  );
}
